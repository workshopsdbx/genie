"""Generate site/content.js from the DOMAINS answer key in the notebook, plus trap answers.

Usage: python3 build_site_content.py [answers.json]
The catalog is emitted as {{CATALOG}} and substituted in the browser from site/config.js.
"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).parent
src = (ROOT / "genie_byoq_nyc_workshop.py").read_text()
start = src.index("A = f\"{CATALOG}.{SCHEMA_AGING}\"")
end = src.index("# COMMAND ----------", start)
ns = {"CATALOG": "{{CATALOG}}", "SCHEMA_AGING": "nyc_aging_home_care",
      "SCHEMA_TRANSIT": "nyc_transit_finance", "SCHEMA_WATER": "nyc_dep_water",
      "SCHEMA_HEALTH": "nyc_dohmh_food_safety"}
exec(src[start:end], ns)

REL = {"MANY_TO_ONE": "Many to one", "ONE_TO_MANY": "One to many", "ONE_TO_ONE": "One to one", "MANY_TO_MANY": "Many to many"}
domains = {}
for key, d in ns["DOMAINS"].items():
    domains[key] = {
        "title": d["title"],
        "instructions": d["curated_instructions"],
        "joins": [{"left": l, "right": r, "on": on, "rel": REL[rt]} for l, r, on, rt in d["joins"]],
        "measures": [{"alias": a, "name": n, "sql": s, "synonyms": syn} for a, n, s, syn in d["measures"]],
        "examples": [{"question": q, "sql": s} for q, s in d["example_sqls"]],
        "benchmarks": [{"question": q, "sql": s} for q, s in d["benchmarks"]],
        "trusted": {"question": d["trusted"][0], "sql": d["trusted"][1],
                    "params": [{"name": n, "type": t, "example": v} for n, (t, v) in d["trusted"][2].items()]},
        "metric_view": {
            "name": d["metric_view"][0],
            "fq": f"{{{{CATALOG}}}}.{d['schema']}.{d['metric_view'][0]}",
            "create": f"CREATE OR REPLACE VIEW {{{{CATALOG}}}}.{d['schema']}.{{{{INITIALS}}}}_{d['metric_view'][0]}\n"
                      f"WITH METRICS\nLANGUAGE YAML\nAS $$\n{d['metric_view'][1]}$$",
            "query": d["metric_view"][2],
        },
    }

answers = json.loads(pathlib.Path(sys.argv[1]).read_text()) if len(sys.argv) > 1 else {}
out = ("// Generated by build_site_content.py from the notebook answer key. Do not edit by hand.\n"
       f"window.WORKSHOP_CONTENT = {json.dumps({'domains': domains, 'answers': answers}, indent=1)};\n")
(ROOT / "site" / "content.js").write_text(out)
print(f"wrote site/content.js ({len(out):,} bytes, {len(answers)} answers)")
